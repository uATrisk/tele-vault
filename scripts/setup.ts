// Interactive setup script for TeleVault
import * as readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';
import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';

async function main() {
  const rl = readline.createInterface({ input, output });

  console.log('========================================');
  console.log('   TeleVault Human Setup Assistant      ');
  console.log('========================================\n');

  const botToken = await rl.question('Enter your Telegram Bot Token: ');
  const chatId = await rl.question('Enter your Telegram Private Channel ID (e.g. -100123456789): ');

  if (!botToken.trim() || !chatId.trim()) {
    console.error('❌ Bot Token and Channel ID cannot be empty.');
    rl.close();
    process.exit(1);
  }

  // Generate 256-bit secure access token and session secret
  const accessToken = 'tv_' + crypto.randomBytes(24).toString('base64url');
  const sessionSecret = crypto.randomBytes(32).toString('hex');

  const devVarsContent = `# Auto-generated by npm run setup on ${new Date().toISOString()}
TELEGRAM_BOT_TOKEN=${botToken.trim()}
TELEGRAM_CHAT_ID=${chatId.trim()}
ACCESS_TOKEN=${accessToken}
SESSION_SECRET=${sessionSecret}
ENVIRONMENT=dev
`;

  const devVarsPath = path.join(process.cwd(), '.dev.vars');
  const workerDevVarsPath = path.join(process.cwd(), 'apps/worker/.dev.vars');
  fs.writeFileSync(devVarsPath, devVarsContent, { mode: 0o600 });
  fs.writeFileSync(workerDevVarsPath, devVarsContent, { mode: 0o600 });

  console.log('\n✅ Created .dev.vars and apps/worker/.dev.vars.');
  console.log('\n======================================================');
  console.log('🔑 YOUR WEB ACCESS TOKEN (SAVE IN PASSWORD MANAGER):');
  console.log(`   ${accessToken}`);
  console.log('======================================================');
  console.log('This token is needed to log into the TeleVault web app.');
  console.log('It will not be displayed again.\n');

  rl.close();
}

main().catch((err) => {
  console.error('Setup failed:', err);
  process.exit(1);
});
